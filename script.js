// =====================================================
// CART
// =====================================================

let cart = [];


// =====================================================
// DISPLAY PETS
// =====================================================

function displayPets(list) {

    const petGrid = document.getElementById("petGrid");
    const noResults = document.getElementById("noResults");
    const resultCount = document.getElementById("resultCount");

    petGrid.innerHTML = "";

    resultCount.textContent = `${list.length} pets found`;

    if (list.length === 0) {
        noResults.style.display = "block";
        return;
    }

    noResults.style.display = "none";

    list.forEach(pet => {

        const card = document.createElement("div");

        card.className = "pet-card";

        card.innerHTML = `

            <div class="pet-image">

                <img
                    src="${pet.image}?auto=format&fit=crop&w=600&q=80"
                    alt="${pet.name}"
                >

                <span class="category-badge">
                    ${pet.category.toUpperCase()}
                </span>

            </div>

            <div class="pet-info">

                <h3>${pet.name}</h3>

                <p class="pet-category">
                    ${pet.category}
                </p>

                <h4>
                    ₹${pet.price.toLocaleString("en-IN")}
                </h4>

                <button
                    class="add-cart"
                    onclick="addPetToCart(${pet.id})">

                    🛒 Add to Cart

                </button>

            </div>
        `;

        petGrid.appendChild(card);

    });
}


// =====================================================
// SEARCH + FILTER
// =====================================================

function searchPets() {

    const searchInput =
        document.getElementById("searchInput")
        .value
        .toLowerCase()
        .trim();

    const category =
        document.getElementById("categoryFilter").value;

    const price =
        document.getElementById("priceFilter").value;


    const filteredPets = pets.filter(pet => {

        const searchMatch =
            pet.name.toLowerCase().includes(searchInput) ||
            pet.category.toLowerCase().includes(searchInput);


        const categoryMatch =
            category === "all" ||
            pet.category === category;


        let priceMatch = true;


        if (price === "low") {
            priceMatch = pet.price < 5000;
        }

        if (price === "medium") {
            priceMatch =
                pet.price >= 5000 &&
                pet.price <= 15000;
        }

        if (price === "high") {
            priceMatch = pet.price > 15000;
        }


        return (
            searchMatch &&
            categoryMatch &&
            priceMatch
        );

    });


    displayPets(filteredPets);
}


// =====================================================
// FILTER
// =====================================================

function filterPets() {
    searchPets();
}


// =====================================================
// ADD TO CART
// =====================================================

function addPetToCart(id) {

    const pet = pets.find(item => item.id === id);

    if (!pet) {
        return;
    }


    const existingPet =
        cart.find(item => item.id === id);


    if (existingPet) {

        existingPet.quantity++;

    } else {

        cart.push({
            ...pet,
            quantity: 1
        });

    }


    updateCart();

    alert(`${pet.name} added to cart!`);
}


// =====================================================
// UPDATE CART
// =====================================================

function updateCart() {

    const cartCount =
        document.getElementById("cartCount");


    const totalQuantity =
        cart.reduce(
            (total, item) =>
                total + item.quantity,
            0
        );


    cartCount.textContent = totalQuantity;

    displayCart();
}


// =====================================================
// DISPLAY CART
// =====================================================

function displayCart() {

    const cartItems =
        document.getElementById("cartItems");

    const cartTotal =
        document.getElementById("cartTotal");


    cartItems.innerHTML = "";


    if (cart.length === 0) {

        cartItems.innerHTML =
            "<p>Your cart is empty 🛒</p>";

        cartTotal.textContent = "0";

        return;
    }


    let total = 0;


    cart.forEach(item => {

        total +=
            item.price * item.quantity;


        const cartItem =
            document.createElement("div");


        cartItem.className =
            "cart-item";


        cartItem.innerHTML = `

            <div>

                <strong>
                    ${item.name}
                </strong>

                <p>
                    ₹${item.price.toLocaleString("en-IN")}
                </p>

            </div>

            <div class="quantity">

                <button
                    onclick="changeQuantity(${item.id}, -1)">
                    -
                </button>

                <span>
                    ${item.quantity}
                </span>

                <button
                    onclick="changeQuantity(${item.id}, 1)">
                    +
                </button>

            </div>

            <button
                class="remove-btn"
                onclick="removeFromCart(${item.id})">

                ❌

            </button>
        `;


        cartItems.appendChild(cartItem);

    });


    cartTotal.textContent =
        total.toLocaleString("en-IN");
}


// =====================================================
// CHANGE QUANTITY
// =====================================================

function changeQuantity(id, change) {

    const item =
        cart.find(pet => pet.id === id);


    if (!item) {
        return;
    }


    item.quantity += change;


    if (item.quantity <= 0) {

        cart =
            cart.filter(pet => pet.id !== id);

    }


    updateCart();
}


// =====================================================
// REMOVE FROM CART
// =====================================================

function removeFromCart(id) {

    cart =
        cart.filter(pet => pet.id !== id);

    updateCart();
}


// =====================================================
// CART MODAL
// =====================================================

function openCart() {

    document.getElementById("cartModal")
        .style.display = "flex";

    displayCart();
}


function closeCart() {

    document.getElementById("cartModal")
        .style.display = "none";
}


// =====================================================
// ORDER FORM
// =====================================================

function openOrderForm() {

    if (cart.length === 0) {

        alert("Please add a pet to cart first.");

        return;
    }


    document.getElementById("orderModal")
        .style.display = "flex";
}


function closeOrderForm() {

    document.getElementById("orderModal")
        .style.display = "none";
}


// =====================================================
// PLACE ORDER
// =====================================================

function placeOrder(event) {

    event.preventDefault();


    const name =
        document.getElementById("customerName").value;


    alert(
        `Thank you ${name}! 🎉\n\n` +
        `Your PetNest order has been placed successfully.\n\n` +
        `Payment: Cash on Delivery`
    );


    cart = [];

    updateCart();

    closeOrderForm();

    closeCart();
}


// =====================================================
// CLOSE MODAL OUTSIDE CLICK
// =====================================================

window.onclick = function(event) {

    const cartModal =
        document.getElementById("cartModal");

    const orderModal =
        document.getElementById("orderModal");


    if (event.target === cartModal) {
        closeCart();
    }


    if (event.target === orderModal) {
        closeOrderForm();
    }

};


